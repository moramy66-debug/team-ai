/* Review prompt builder: turns a calculation result into a self-contained prompt
   the user can paste into any other AI model. It only builds text; it never sends anything. */
(function (g) {
  'use strict';
  var NA = 'not recorded';

  function clean(v) { return String(v == null ? '' : v).replace(/\s+/g, ' ').trim(); }

  function sourceLine(u, n) {
    if (g.SourceInfo && g.SourceInfo.text) return g.SourceInfo.text(u, n);
    return '[' + n + '] ' + clean(u.id) + ' | status: ' + clean(u.status || NA) + ' | source: ' + clean(u.source || NA);
  }

  function build(o) {
    o = o || {};
    var res = o.res || {}, L = [];
    var steps = res.steps || [], used = res.tablesUsed || [], warns = (res.warnings || []).filter(function (w, i, a) { return a.indexOf(w) === i; });
    L.push('# Engineering calculation review request');
    L.push('');
    L.push('Calculation type: ' + clean(o.title || 'Calculation'));
    L.push('Generated by Ramz (deterministic calculator). The numbers below were computed by code, not by an AI model.');
    L.push('');
    L.push('## 1. Inputs (with units)');
    var inputs = (o.inputs || []).filter(function (i) { return i && clean(i.label); });
    if (inputs.length) inputs.forEach(function (i) { L.push('- ' + clean(i.label) + ': ' + (clean(i.value) === '' ? '(empty, default used)' : clean(i.value))); });
    else L.push('- Inputs were not captured. Ask the user for them before reviewing.');
    L.push('');
    L.push('## 2. Assumptions, defaults and warnings');
    if (warns.length) warns.forEach(function (w) { L.push('- ' + clean(w)); });
    else L.push('- None reported by the calculator.');
    var fm = steps.map(function (s) { return String(s.formula || ''); }).join(' | ');
    if (/Ib <= In <= Iz/.test(fm)) L.push('- Protection condition I2 <= 1.45 Iz was NOT calculated separately. Only Ib <= In <= Iz was checked. Confirm I2 from the manufacturer data.');
    if (/Ca /.test(fm)) L.push('- Ambient temperature warning: the chosen ambient may be low for hot-climate sites. Ca changes with ambient, and a different Ca can change the selected cross-section. Re-run with the real site ambient and check the Ca source table.');
    L.push('');
    L.push('## 3. Calculation steps (formula, substitution, result)');
    if (steps.length) steps.forEach(function (s, i) {
      L.push((i + 1) + '. ' + clean(s.step));
      L.push('   Formula: ' + clean(s.formula));
      L.push('   Substitution: ' + clean(s.substitution));
      L.push('   Result: ' + clean(s.result));
    });
    else L.push('- No steps were returned.');
    L.push('');
    L.push('## 4. Final result');
    L.push(clean(res.summary) || 'No summary returned.');
    L.push('');
    L.push('## 5. Sources and their status');
    if (used.length) used.forEach(function (u, i) { L.push(sourceLine(u, i + 1)); });
    else L.push('- No source table was recorded for this calculation.');
    L.push('Status meaning: verified_secondary = taken from a published secondary source or public copy, not the official standard text. needs_review or from_memory_needs_review = not confirmed, treat as unverified. "not recorded" for page, clause or edition means the data does not hold it.');
    L.push('');
    L.push('## 6. Your task (reviewing model)');
    L.push('You are a senior electrical engineer reviewing the calculation above. Follow these rules:');
    L.push('1. Recompute every step independently from the inputs. Do not copy the results above.');
    L.push('2. Flag any arithmetic error, wrong formula, wrong unit or unit conversion, and any input or default that looks unrealistic.');
    L.push('3. Check the assumptions and the cited standards (IEC 60364, BS 7671, SBC 401 or others named above) against what you know. Say which method or table applies.');
    L.push('4. List every value you could not verify and say why. Do not guess.');
    L.push('5. Do not invent clause numbers, table numbers, page numbers or editions. If you are not sure of a reference, write "not verified".');
    L.push('6. Treat needs_review items as unverified, and do not upgrade their status.');
    L.push('7. Answer as a prioritized list. For each finding give: severity (Critical, Major, Minor or Info), the step number, what is wrong or doubtful, and the suggested correction.');
    L.push('8. End with a short verdict: Accept, Accept with comments, or Reject, and the reason.');
    L.push('Write the answer in Arabic with English technical terms (Power Factor, Voltage Drop, Breaker and so on).');
    return L.join('\n');
  }

  function collectInputs(container) {
    var node = container, fields = [];
    while (node && node !== document.body) {
      fields = node.querySelectorAll ? node.querySelectorAll('.ec-field') : [];
      if (fields.length) break;
      node = node.parentElement;
    }
    var out = [];
    Array.prototype.forEach.call(fields, function (f) {
      var lb = f.querySelector('label'), ctl = f.querySelector('input,select,textarea');
      if (!lb || !ctl) return;
      var v = ctl.tagName === 'SELECT' ? (ctl.options[ctl.selectedIndex] ? ctl.options[ctl.selectedIndex].text : '') : ctl.value;
      out.push({ label: lb.textContent, value: v });
    });
    return out;
  }


  var CSS = '.rpx-toast{position:fixed;left:50%;bottom:calc(20px + env(safe-area-inset-bottom));transform:translateX(-50%);z-index:10001;max-width:90vw;background:var(--card,#181b22);color:var(--tx,#e8eaf0);border:1px solid var(--ac,#6366f1);border-radius:12px;padding:10px 14px;font-size:14px;box-shadow:0 8px 30px rgba(0,0,0,.4);direction:rtl;text-align:center}' +
    '.rpx-bd{position:fixed;inset:0;z-index:10000;background:rgba(5,8,15,.6);display:flex;align-items:flex-end;justify-content:center}' +
    '.rpx-sheet{width:100%;max-width:640px;max-height:85vh;overflow:auto;box-sizing:border-box;background:var(--card,#181b22);color:var(--tx,#e8eaf0);border:1px solid var(--line,#2a2f3a);border-radius:16px 16px 0 0;padding:14px;direction:rtl}' +
    '.rpx-sheet textarea{width:100%;height:46vh;box-sizing:border-box;font-size:16px;direction:ltr;text-align:left;margin:8px 0}' +
    '.rpx-sheet button{min-height:44px}';
  var styled = false;
  function style() { if (styled) return; styled = true; var st = document.createElement('style'); st.textContent = CSS; document.head.appendChild(st); }

  function toast(msg) {
    style();
    var t = document.createElement('div'); t.className = 'rpx-toast'; t.setAttribute('role', 'status'); t.textContent = msg;
    document.body.appendChild(t);
    setTimeout(function () { if (t.parentNode) t.parentNode.removeChild(t); }, 2600);
  }

  /* manual copy panel: select-all textarea, works where the clipboard API is blocked (iOS) */
  function fallback(text) {
    style();
    var bd = document.createElement('div'); bd.className = 'rpx-bd';
    var sh = document.createElement('div'); sh.className = 'rpx-sheet'; sh.setAttribute('role', 'dialog'); sh.setAttribute('aria-modal', 'true');
    var p = document.createElement('p'); p.textContent = 'النسخ التلقائي مش متاح هنا. اضغط جوه الخانة، حدد الكل، وانسخ يدوي.';
    var ta = document.createElement('textarea'); ta.value = text; ta.readOnly = true; ta.setAttribute('aria-label', 'Review prompt');
    var sel = document.createElement('button'); sel.type = 'button'; sel.textContent = 'Select all';
    var cl = document.createElement('button'); cl.type = 'button'; cl.textContent = 'Close'; cl.style.marginInlineStart = '8px';
    sel.onclick = function () { ta.focus(); ta.setSelectionRange(0, ta.value.length); try { document.execCommand('copy'); } catch (e) { } };
    cl.onclick = function () { if (bd.parentNode) bd.parentNode.removeChild(bd); };
    bd.addEventListener('click', function (e) { if (e.target === bd) cl.onclick(); });
    sh.appendChild(p); sh.appendChild(ta); sh.appendChild(sel); sh.appendChild(cl); bd.appendChild(sh); document.body.appendChild(bd);
    ta.focus(); ta.setSelectionRange(0, ta.value.length);
  }

  function copy(text) {
    function viaExec() {
      var ta = document.createElement('textarea'); ta.value = text; ta.setAttribute('readonly', '');
      ta.style.cssText = 'position:fixed;top:0;left:0;opacity:0;font-size:16px';
      document.body.appendChild(ta); ta.focus(); ta.setSelectionRange(0, ta.value.length);
      var ok = false; try { ok = document.execCommand('copy'); } catch (e) { }
      document.body.removeChild(ta); return ok;
    }
    function done() { toast('تم نسخ الـ Review Prompt. الصقه في أي AI.'); }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text).then(done, function () { if (viaExec()) done(); else fallback(text); });
    }
    if (viaExec()) done(); else fallback(text);
    return Promise.resolve();
  }


  /* chat/AI result: no structured steps, so build from the task text and the final answer */
  function buildChat(o) {
    o = o || {};
    var L = [];
    L.push('# Review request for an AI-generated answer');
    L.push('');
    L.push('The answer below was produced by an AI model inside Ramz. It was NOT computed by a deterministic calculator, so every number and every reference in it is unverified.');
    L.push('');
    L.push('## 1. The task that was given');
    L.push(String(o.task == null ? '' : o.task).trim() || '(task text not captured, ask the user for it)');
    L.push('');
    L.push('## 2. The answer to review');
    L.push(String(o.answer == null ? '' : o.answer).trim() || '(empty)');
    L.push('');
    L.push('## 3. Your task (reviewing model)');
    L.push('You are a senior engineer reviewing the answer above. Follow these rules:');
    L.push('1. Check the answer against the task. Say what it missed or got wrong.');
    L.push('2. Recompute every number and unit conversion yourself. Do not trust the figures given.');
    L.push('3. Flag any formula, standard, clause, table, page or edition that you cannot confirm. Write "not verified" instead of guessing.');
    L.push('4. Do not invent clause numbers, table numbers, page numbers or editions.');
    L.push('5. Answer as a prioritized list. For each finding give: severity (Critical, Major, Minor or Info), where in the answer, what is wrong or doubtful, and the suggested correction.');
    L.push('6. End with a short verdict: Accept, Accept with comments, or Reject, and the reason.');
    L.push('Write the answer in Arabic with English technical terms (Power Factor, Voltage Drop, Breaker and so on).');
    return L.join('\n');
  }

  function mountChatButton() {
    var host = document.getElementById('copy');
    if (!host || document.getElementById('chatRevBtn')) return;
    var b = document.createElement('button');
    b.id = 'chatRevBtn'; b.type = 'button'; b.className = 'sec i-copy'; b.textContent = 'Review Prompt';
    b.title = 'Copy a prompt that asks another AI to review this answer';
    b.addEventListener('click', function () {
      var fin = document.getElementById('final'), task = document.getElementById('task');
      var answer = fin ? fin.textContent : '';
      var first = document.querySelector('#thread .msg');
      var t = (task && task.value) || (first ? first.textContent : '');
      if (!String(answer).trim()) { toast('مفيش نتيجة تتراجع لسه.'); return; }
      copy(buildChat({ task: t, answer: answer }));
    });
    host.parentNode.insertBefore(b, host);
  }
  if (typeof document !== 'undefined' && document.getElementById && document.addEventListener) {
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', mountChatButton); else mountChatButton();
  }

  g.ReviewPrompt = { buildChat: buildChat, build: build, collectInputs: collectInputs, copy: copy };
})(window);
