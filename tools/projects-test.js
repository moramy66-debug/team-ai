'use strict';
var path = require('path');
global.window = global;
global.document = {};
require(path.join(__dirname, '../js/projects.js'));
var C = window.Projects.core;
var fails = 0;
function ok(n, c) { if (!c) { fails++; console.log('FAIL ' + n); } else console.log('ok   ' + n); }
var saved = null;
C.init({ get: function () { return saved; }, set: function (s) { saved = s; } }, null);
ok('starts empty', C.state().projects.length === 0);
var p = C.create('  Tower   A  ');
ok('create trims and collapses spaces', p && p.name === 'Tower A');
ok('empty name rejected', C.create('   ') === null);
ok('persisted as JSON', JSON.parse(saved).projects.length === 1);
ok('rename', C.rename(p.id, 'Tower B') && C.get(p.id).name === 'Tower B');
ok('rename to empty rejected', !C.rename(p.id, ' ') && C.get(p.id).name === 'Tower B');
ok('no notes gives empty context', C.context(p.id) === '');
ok('add note', C.addNote(p.id, 'Voltage 400 V, 3 Phase').ok);
ok('empty note rejected', C.addNote(p.id, '  ').reason === 'empty');
var ctx = C.context(p.id);
ok('context has name and numbered note', /Project: Tower B/.test(ctx) && /1\. Voltage 400 V, 3 Phase/.test(ctx));
var big = new Array(401).join('x');
ok('note is cut to the per-note limit', C.addNote(p.id, big + big).ok && C.get(p.id).notes[1].text.length === C.MAX_NOTE_CHARS);
var before = C.size(C.get(p.id));
C.addNote(p.id, new Array(600).join('z'));
before = C.size(C.get(p.id));
var r = C.addNote(p.id, new Array(600).join('y'));
ok('over the total limit is refused', r.ok === false && r.reason === 'too_big' && C.size(C.get(p.id)) === before);
var n0 = C.get(p.id).notes.length, firstId = C.get(p.id).notes[0].id;
ok('delete note', C.delNote(p.id, firstId) && C.get(p.id).notes.length === n0 - 1 && !C.get(p.id).notes.some(function (n) { return n.id === firstId; }));
ok('assign chat', C.assign('chat1', p.id) && C.projectOf('chat1') === p.id);
ok('unknown chat has no project (default bucket)', C.projectOf('old-chat') === null);
ok('assign to missing project refused', C.assign('chat2', 'nope') === false && C.projectOf('chat2') === null);
ok('unassign', C.assign('chat1', null) && C.projectOf('chat1') === null);
C.assign('chat1', p.id); C.setActive(p.id);
ok('active set', C.state().active === p.id);
var q = C.create('Other');
ok('remove project keeps chats out of it', C.remove(p.id) && C.projectOf('chat1') === null && C.state().active === null && C.state().projects.length === 1 && C.get(q.id));
var snapshot = JSON.parse(saved);
C.init({ get: function () { return saved; }, set: function (s) { saved = s; } }, snapshot);
ok('reload from saved state', C.state().projects.length === 1 && C.get(q.id).name === 'Other');
C.init(null, { projects: [{ id: 'a', name: 'ok', notes: [{ text: 'n' }, { text: '' }] }, { id: '', name: 'bad' }, null], chatMap: { c1: 'a', c2: 'ghost' }, active: 'ghost' });
ok('bad data cleaned', C.state().projects.length === 1 && C.get('a').notes.length === 1 && C.projectOf('c1') === 'a' && C.projectOf('c2') === null && C.state().active === null);
for (var i = 0; i < 40; i++) C.create('P' + i);
ok('project count capped', C.state().projects.length <= 30);
ok('no emoji in context', !/[\u{1F300}-\u{1FAFF}]/u.test(C.context('a')));
if (fails) { console.log(fails + ' FAILED'); process.exit(1); }
console.log('ALL PROJECTS TESTS PASSED');
